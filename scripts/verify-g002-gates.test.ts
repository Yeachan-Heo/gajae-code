function registryWithEntries(entries: readonly string[]): string {
	return [
		"const BUILTIN_SLASH_COMMAND_REGISTRY = [",
		...entries.flatMap(entry => ["\t{", entry, "\t},"]),
		"];",
	].join("\n");
}

