/**
 * Render a gjc hook module from imported foreign hook commands.
 *
 * Claude Code hooks are shell commands: the runtime writes a JSON payload to
 * stdin and reads the exit code. `PreToolUse` blocks on exit 2 with stderr as the
 * reason; every other event is observational. gjc hooks are TypeScript modules
 * that subscribe to events in-process, so the importer reproduces the foreign
 * contract rather than rewriting the commands.
 *
 * Only events whose semantics are unambiguous are translated. The payload keeps
 * the foreign field names so an existing script that reads its JSON keeps working;
 * fields this host cannot supply are omitted instead of guessed, which the module
 * header states.
 */
import type { HookCandidate, MigrateSource } from "./types";

/** Foreign event -> gjc hook event. Blocking events are marked separately. */
/** Maximum time (ms) to wait for a hook command to complete. Prevents indefinite hangs. */
const HOOK_COMMAND_TIMEOUT_MS = 30000;

const EVENT_MAP: Record<string, { event: string; blocking: boolean }> = {
	PreToolUse: { event: "tool_call", blocking: true },
	PostToolUse: { event: "tool_result", blocking: false },
	SessionStart: { event: "session_start", blocking: false },
};

export function isSupportedHookEvent(event: string): boolean {
	return event in EVENT_MAP;
}

/** Foreign events this importer translates, for user-facing messages. */
export const SUPPORTED_HOOK_EVENTS: readonly string[] = Object.keys(EVENT_MAP);

interface RenderedHook {
	event: string;
	blocking: boolean;
	matcher?: string;
	command: string;
	sourceEvent: string;
}

function constantName(event: string): string {
	return event.replace(/[^a-z_]/g, "_").toUpperCase();
}

function renderHookLiteral(hook: RenderedHook): string {
	const parts = [`event: ${JSON.stringify(hook.sourceEvent)}`, `command: ${JSON.stringify(hook.command)}`];
	if (hook.matcher) parts.push(`matcher: ${JSON.stringify(hook.matcher)}`);
	return `\t{ ${parts.join(", ")} },`;
}

/**
 * Build the module source. The result is deterministic for a given candidate
 * list, so a dry-run report and a live write describe the same file.
 */
export function renderHookModule(source: MigrateSource, candidates: readonly HookCandidate[]): string {
	const hooks: RenderedHook[] = [];
	for (const candidate of candidates) {
		const mapped = EVENT_MAP[candidate.event];
		if (!mapped) continue;
		hooks.push({
			event: mapped.event,
			blocking: mapped.blocking,
			matcher: candidate.matcher,
			command: candidate.command,
			sourceEvent: candidate.event,
		});
	}
	const byEvent = new Map<string, RenderedHook[]>();
	for (const hook of hooks) {
		const list = byEvent.get(hook.event) ?? [];
		list.push(hook);
		byEvent.set(hook.event, list);
	}
	const eventNames = [...byEvent.keys()].sort();
	const blocks = eventNames
		.map(event => {
			const entries = (byEvent.get(event) ?? []).map(renderHookLiteral).join("\n");
			return `const ${constantName(event)}_HOOKS: readonly ImportedHook[] = [\n${entries}\n];`;
		})
		.join("\n\n");
	const registrations = eventNames
		.map(event => {
			const blocking = byEvent.get(event)?.some(hook => hook.blocking) ?? false;
			const register = blocking ? "registerBlocking" : "registerObservational";
			return `\t${register}(api, ${JSON.stringify(event)}, ${constantName(event)}_HOOKS);`;
		})
		.join("\n");

	return `/**
 * Generated by \`gjc migrate --from ${source}\`. Re-run with --force to regenerate.
 *
 * These hooks were shell commands in ${source}. Each command receives a JSON
 * payload on stdin under the origin's field names; fields this runtime cannot
 * supply (session id, transcript path) are omitted rather than invented.
 * \`PreToolUse\` blocks the tool when the command exits 2 and uses its stderr as
 * the reason, which is the origin contract; the other events only run the
 * command.
 */
import { spawn } from "node:child_process";

interface ImportedHook {
	event: string;
	command: string;
	matcher?: string;
}

interface HookCommandResult {
	code: number;
	stdout: string;
	stderr: string;
}

interface HookApi {
	on(event: string, handler: (payload: unknown, context: { cwd?: string }) => unknown): void;
}

/** Maximum time (ms) to wait for a hook command to complete. Prevents indefinite hangs. */
const HOOK_COMMAND_TIMEOUT_MS = 30000;

${blocks}

function matches(matcher: string | undefined, toolName: string | undefined): boolean {
	if (!matcher || !matcher.trim()) return true;
	if (!toolName) return false;
	// Normalize tool name to lowercase (Claude Code tools are capitalized, GJC tools are lowercase)
	const normalizedName = toolName.toLowerCase();
	try {
		return new RegExp(\`^(?:\${matcher})$\`, "i").test(normalizedName);
	} catch {
		return matcher.toLowerCase() === normalizedName;
	}
}

function shellCommand(command: string): string[] {
	return process.platform === "win32"
		? [process.env.ComSpec ?? "cmd.exe", "/d", "/s", "/c", command]
		: ["/bin/bash", "-lc", command];
}

async function runHook(hook: ImportedHook, payload: unknown): Promise<HookCommandResult> {
	const [file, ...args] = shellCommand(hook.command);
	const child = spawn(file, args, { stdio: ["pipe", "pipe", "pipe"] });
	child.stdin?.end(JSON.stringify(payload));
	let stdout = "";
	let stderr = "";
	child.stdout?.on("data", chunk => {
		stdout += String(chunk);
	});
	child.stderr?.on("data", chunk => {
		stderr += String(chunk);
	});
	// Use Promise.race to enforce timeout
	const code = await Promise.race<number>([
		new Promise<number>(resolve => {
			child.on("error", () => resolve(1));
			child.on("close", value => resolve(value ?? 1));
		}),
		new Promise<number>(resolve => {
			setTimeout(() => {
				child.kill();
				resolve(124); // Standard timeout exit code
			}, HOOK_COMMAND_TIMEOUT_MS);
		}),
	]);
	return { code, stdout, stderr };
}

function registerBlocking(api: HookApi, event: string, hooks: readonly ImportedHook[]): void {
	api.on(event, async (payload, context) => {
		const record = payload as { toolName?: string; input?: unknown };
		for (const hook of hooks) {
			if (!matches(hook.matcher, record?.toolName)) continue;
			const result = await runHook(hook, {
				hook_event_name: hook.event,
				tool_name: record?.toolName,
				tool_input: record?.input,
				cwd: context?.cwd,
			});
			// Check for explicit deny in JSON response (exit 0 with permissionDecision: "deny")
			if (result.code === 0 && result.stdout.trim()) {
				try {
					const response = JSON.parse(result.stdout) as { permissionDecision?: string };
					if (response.permissionDecision === "deny") {
						return { block: true, reason: \`denied by \${hook.event} hook\` };
					}
				} catch {
					// Not JSON or parse failed; check exit code
				}
			}
			// Standard Claude Code convention: exit 2 means block
			if (result.code === 2) {
				return { block: true, reason: result.stderr.trim() || \`blocked by imported \${hook.event} hook\` };
			}
		}
		return undefined;
	});
}

function registerObservational(api: HookApi, event: string, hooks: readonly ImportedHook[]): void {
	api.on(event, async (payload, context) => {
		const record = payload as {
			toolName?: string;
			input?: unknown;
			turnIndex?: number;
			content?: unknown;
			isError?: boolean;
		};
		for (const hook of hooks) {
			if (event === "tool_result" && !matches(hook.matcher, record?.toolName)) continue;
			const hookPayload: Record<string, unknown> = {
				hook_event_name: hook.event,
				tool_name: record?.toolName,
				tool_input: record?.input,
				turn_index: record?.turnIndex,
				cwd: context?.cwd,
			};
			// Translate tool_response fields for PostToolUse events
			if (event === "tool_result" && record?.content !== undefined) {
				hookPayload.tool_response = record.content;
			}
			if (event === "tool_result" && record?.isError !== undefined) {
				hookPayload.tool_error = record.isError;
			}
			await runHook(hook, hookPayload);
		}
		return undefined;
	});
}

export default (api: HookApi): void => {
${registrations}
};
`;
}
