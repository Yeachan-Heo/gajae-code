function applyPatchRenameAfterUpdate(firstDiff: string, moveTo: string): Promise<AgentToolResult<unknown>> {
	const tool = new EditTool(makeSession(tempDir, true), "apply_patch");
	const input = [
		"*** Begin Patch",
		"*** Update File: output.ts",
		"@@",
		...firstDiff.split("\n"),
		"*** Update File: product.ts",
		`*** Move to: ${moveTo}`,
		"@@",
		"-line",
		"+moved",
		"*** End Patch",
	].join("\n");
	return tool.execute("apply-patch-rename-after-update", { input });
}

it("refuses a later rename after an earlier entry writes a generated header", async () => {
	const outputPath = path.join(tempDir, "output.ts");
	await Bun.write(outputPath, "hand\n");
	await Bun.write(path.join(tempDir, "product.ts"), SOURCE);

	const result = await applyPatchRenameAfterUpdate(
		"-hand\n+// Code generated by sqlc. DO NOT EDIT.\n+export const kept = 1;",
		"output.ts",
	);

	const text = result.content?.find(block => block.type === "text")?.text ?? "";
	expect(text).toContain("Cannot modify auto-generated file");
	expect(await Bun.file(outputPath).text()).toContain("Code generated by sqlc");
	expect(await Bun.file(outputPath).text()).not.toBe(MOVED);
	expect(await Bun.file(path.join(tempDir, "product.ts")).text()).toBe(SOURCE);
});

it("still allows a later rename after an earlier entry leaves the destination handwritten", async () => {
	const outputPath = path.join(tempDir, "output.ts");
	await Bun.write(outputPath, "hand\n");
	await Bun.write(path.join(tempDir, "product.ts"), SOURCE);

	const result = await applyPatchRenameAfterUpdate("-hand\n+note", "output.ts");

	expect(result.isError).toBeUndefined();
	expect(await Bun.file(outputPath).text()).toBe(MOVED);
	expect(await Bun.file(path.join(tempDir, "product.ts")).exists()).toBe(false);
});

it("aborts a multi-entry patch between destination checks", async () => {
	await Bun.write(path.join(tempDir, "product.ts"), SOURCE);
	const controller = new AbortController();
	let calls = 0;
	const spy = vi.spyOn(autoGeneratedGuard, "assertEditableFile").mockImplementation(async () => {
		calls += 1;
		if (calls === 1) controller.abort();
	});
	const tool = new EditTool(makeSession(tempDir, true), "patch");
	try {
		await expect(
			tool.execute(
				"patch-abort-between",
				{
					path: "product.ts",
					edits: [
						{ op: "update", diff: DIFF },
						{ op: "update", diff: "@@\n-moved\n+again" },
					],
				},
				controller.signal,
			),
		).rejects.toThrow(/abort/i);
	} finally {
		spy.mockRestore();
	}
	expect(calls).toBe(1);
	expect(await Bun.file(path.join(tempDir, "product.ts")).text()).toBe(SOURCE);
});

