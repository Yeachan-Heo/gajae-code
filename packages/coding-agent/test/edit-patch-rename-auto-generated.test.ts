const GENERATED_DEST = "// Code generated by sqlc. DO NOT EDIT.\nexport const foo = 1;\n";

/**
 * Hold the destination mutation lock, start a public patch rename, and run
 * `whileBlocked` only after that rename has entered the lock and is waiting.
 */
async function renameWhileDestLocked(
	destName: string,
	whileBlocked: (destAbs: string) => Promise<void>,
): Promise<AgentToolResult<unknown>> {
	const destAbs = path.resolve(tempDir, destName);
	let releaseHold = (): void => {};
	const entered = Promise.withResolvers<void>();
	const hold = pathMutationLock.withEditPathMutation(
		[destAbs],
		async () => {
			entered.resolve();
			await new Promise<void>(resolve => {
				releaseHold = resolve;
			});
		},
		{ crossProcess: false },
	);
	await entered.promise;

	const blocked = Promise.withResolvers<void>();
	const realLock = pathMutationLock.withEditPathMutation;
	const spy = vi.spyOn(pathMutationLock, "withEditPathMutation").mockImplementation((paths, fn, opts) => {
		blocked.resolve();
		return realLock(paths, fn, opts);
	});
	const pending = patchRename(true, "product.ts", destName);
	try {
		const arrived = await Promise.race([
			blocked.promise.then(() => "blocked" as const),
			pending.then(
				() => "settled" as const,
				() => "settled" as const,
			),
		]);
		if (arrived === "blocked") await whileBlocked(destAbs);
		releaseHold();
		return await pending;
	} finally {
		releaseHold();
		spy.mockRestore();
		await hold;
	}
}

it("refuses a patch rename when a concurrent edit turns the destination generated before the move commits", async () => {
	await writePair("product.ts", "notes.ts", "keep\n");

	await expect(
		renameWhileDestLocked("notes.ts", async destAbs => {
			await Bun.write(destAbs, GENERATED_DEST);
		}),
	).rejects.toThrow(/Cannot modify auto-generated file/);

	expect(await Bun.file(path.join(tempDir, "product.ts")).text()).toBe(SOURCE);
	expect(await Bun.file(path.join(tempDir, "notes.ts")).text()).toBe(GENERATED_DEST);
});

it("still allows a patch rename when a concurrent edit leaves the destination handwritten", async () => {
	await writePair("product.ts", "notes.ts", "keep\n");

	const result = await renameWhileDestLocked("notes.ts", async destAbs => {
		await Bun.write(destAbs, "note\n");
	});

	expect(result.isError).toBeUndefined();
	expect(await Bun.file(path.join(tempDir, "notes.ts")).text()).toBe(MOVED);
	expect(await Bun.file(path.join(tempDir, "product.ts")).exists()).toBe(false);
});
