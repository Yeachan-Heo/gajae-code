import { afterEach, describe, expect, it } from "bun:test";
import * as fs from "node:fs/promises";
import * as os from "node:os";
import * as path from "node:path";
import { resetSettingsForTest, Settings } from "@gajae-code/coding-agent/config/settings";
import type { ToolSession } from "@gajae-code/coding-agent/tools";
import { ToolError } from "@gajae-code/coding-agent/tools/tool-errors";
import { WriteTool } from "@gajae-code/coding-agent/tools/write";
import { YAML } from "bun";
import fc from "fast-check";

const SEED = 62817;
const GENERATED_NAME = "api.pb.go";
const GENERATED_BODY = "package widget\n\nconst X = 1\n";
const GENERATED_NEXT = "package widget\n\nconst X = 2\n";
const HAND_NAME = "notes.ts";
const HAND_BODY = "// Generated by the author for local notes.\nexport const value = 1;\n";
const HAND_NEXT = "// Generated by the author for local notes.\nexport const value = 2;\n";
const MARKED_NAME = "hand.ts";
const MARKED_BODY = "// Code generated by sqlc. DO NOT EDIT.\nexport const foo = 1;\n";
const MARKED_NEXT = "// Code generated by sqlc. DO NOT EDIT.\nexport const foo = 2;\n";

const roots: string[] = [];

afterEach(async () => {
	resetSettingsForTest();
	for (const root of roots.splice(0)) {
		await fs.rm(root, { recursive: true, force: true });
	}
});

type Surface = "settings" | "config";

async function load(options: {
	userBlock?: boolean;
	project?: Record<string, unknown>;
	surface?: Surface;
	parentProject?: Record<string, unknown>;
	makeProjectDir?: boolean;
}): Promise<{ settings: Settings; project: string }> {
	const root = await fs.mkdtemp(path.join(os.tmpdir(), "gjc-edit-guard-"));
	roots.push(root);
	const project = path.join(root, "proj");
	const agent = path.join(root, "agent");
	await fs.mkdir(project, { recursive: true });
	await fs.mkdir(agent, { recursive: true });
	const globalBody = options.userBlock === undefined ? {} : { edit: { blockAutoGenerated: options.userBlock } };
	await Bun.write(path.join(agent, "config.yml"), YAML.stringify(globalBody));
	if (options.parentProject) {
		await fs.mkdir(path.join(root, ".gjc"), { recursive: true });
		await Bun.write(path.join(root, ".gjc", "settings.json"), JSON.stringify(options.parentProject));
	}
	if (options.makeProjectDir !== false && options.project) {
		await fs.mkdir(path.join(project, ".gjc"), { recursive: true });
		const surface = options.surface ?? "settings";
		if (surface === "settings") {
			await Bun.write(path.join(project, ".gjc", "settings.json"), JSON.stringify(options.project));
		} else {
			await Bun.write(path.join(project, ".gjc", "config.yml"), YAML.stringify(options.project));
		}
	}
	const settings = await Settings.loadReadonly({ cwd: project, agentDir: agent });
	return { settings, project };
}

function session(project: string, settings: Settings): ToolSession {
	return {
		cwd: project,
		hasUI: false,
		enableLsp: false,
		getSessionFile: () => null,
		getSessionSpawns: () => "*",
		getArtifactsDir: () => null,
		getPlanModeState: () => undefined,
		settings,
	} as unknown as ToolSession;
}

async function writeFile(project: string, settings: Settings, name: string, content: string) {
	const tool = new WriteTool(session(project, settings));
	return tool.execute("write-1", { path: path.join(project, name), content });
}

function textOf(result: { content: Array<{ type: string; text?: string }> }): string {
	return result.content.map(part => (part.type === "text" ? (part.text ?? "") : "")).join("\n");
}

describe("project edit.blockAutoGenerated", () => {
	it("refuses to overwrite a generated file when project settings.json turns the guard off", async () => {
		const { settings, project } = await load({
			userBlock: true,
			project: { edit: { blockAutoGenerated: false, streamingAbort: true } },
		});
		try {
			expect(settings.get("edit.blockAutoGenerated")).toBe(true);
			expect(settings.getGlobal("edit.blockAutoGenerated")).toBe(true);
			expect(settings.get("edit.streamingAbort")).toBe(true);
			await Bun.write(path.join(project, GENERATED_NAME), GENERATED_BODY);
			await expect(writeFile(project, settings, GENERATED_NAME, GENERATED_NEXT)).rejects.toThrow(
				/Cannot modify auto-generated file/,
			);
			expect(await Bun.file(path.join(project, GENERATED_NAME)).text()).toBe(GENERATED_BODY);
		} finally {
			await settings.close();
		}
	});

	it("refuses to overwrite a content-marked file when project config.yml turns the guard off", async () => {
		const { settings, project } = await load({
			surface: "config",
			project: { edit: { blockAutoGenerated: false } },
		});
		try {
			expect(settings.get("edit.blockAutoGenerated")).toBe(true);
			await Bun.write(path.join(project, MARKED_NAME), MARKED_BODY);
			await expect(writeFile(project, settings, MARKED_NAME, MARKED_NEXT)).rejects.toThrow(ToolError);
			expect(await Bun.file(path.join(project, MARKED_NAME)).text()).toBe(MARKED_BODY);
		} finally {
			await settings.close();
		}
	});

	it("does not let a runtime override turn the guard off", async () => {
		const { settings, project } = await load({ userBlock: true });
		try {
			settings.override("edit.blockAutoGenerated", false);
			expect(settings.get("edit.blockAutoGenerated")).toBe(true);
			await Bun.write(path.join(project, GENERATED_NAME), GENERATED_BODY);
			await expect(writeFile(project, settings, GENERATED_NAME, GENERATED_NEXT)).rejects.toThrow(
				/Cannot modify auto-generated file/,
			);
			expect(await Bun.file(path.join(project, GENERATED_NAME)).text()).toBe(GENERATED_BODY);
		} finally {
			await settings.close();
		}
	});

	it("still allows a user config false to edit a generated file", async () => {
		const { settings, project } = await load({
			userBlock: false,
			project: { edit: { streamingAbort: true } },
		});
		try {
			expect(settings.get("edit.blockAutoGenerated")).toBe(false);
			expect(settings.get("edit.streamingAbort")).toBe(true);
			await Bun.write(path.join(project, GENERATED_NAME), GENERATED_BODY);
			const result = await writeFile(project, settings, GENERATED_NAME, GENERATED_NEXT);
			expect(textOf(result)).toContain("Successfully wrote");
			expect(await Bun.file(path.join(project, GENERATED_NAME)).text()).toBe(GENERATED_NEXT);
		} finally {
			await settings.close();
		}
	});

	it("still allows a user config false when the project file also sets false", async () => {
		const { settings, project } = await load({
			userBlock: false,
			surface: "config",
			project: { edit: { blockAutoGenerated: false } },
		});
		try {
			expect(settings.get("edit.blockAutoGenerated")).toBe(false);
			await Bun.write(path.join(project, GENERATED_NAME), GENERATED_BODY);
			const result = await writeFile(project, settings, GENERATED_NAME, GENERATED_NEXT);
			expect(textOf(result)).toContain("Successfully wrote");
			expect(await Bun.file(path.join(project, GENERATED_NAME)).text()).toBe(GENERATED_NEXT);
		} finally {
			await settings.close();
		}
	});

	it("a project true does not replace a user config false", async () => {
		const { settings, project } = await load({
			userBlock: false,
			project: { edit: { blockAutoGenerated: true } },
		});
		try {
			expect(settings.get("edit.blockAutoGenerated")).toBe(false);
			expect(settings.getGlobal("edit.blockAutoGenerated")).toBe(false);
			await Bun.write(path.join(project, GENERATED_NAME), GENERATED_BODY);
			const result = await writeFile(project, settings, GENERATED_NAME, GENERATED_NEXT);
			expect(textOf(result)).toContain("Successfully wrote");
			expect(await Bun.file(path.join(project, GENERATED_NAME)).text()).toBe(GENERATED_NEXT);
		} finally {
			await settings.close();
		}
	});

	it("still allows a handwritten file when the project file sets the switch false", async () => {
		const { settings, project } = await load({
			project: { edit: { blockAutoGenerated: false } },
		});
		try {
			await Bun.write(path.join(project, HAND_NAME), HAND_BODY);
			const result = await writeFile(project, settings, HAND_NAME, HAND_NEXT);
			expect(textOf(result)).toContain("Successfully wrote");
			expect(await Bun.file(path.join(project, HAND_NAME)).text()).toBe(HAND_NEXT);
		} finally {
			await settings.close();
		}
	});

	it("still allows a case-variant name when the project file sets the switch false", async () => {
		const { settings, project } = await load({
			surface: "config",
			project: { edit: { blockAutoGenerated: false } },
		});
		try {
			const name = "widget.PB.go";
			await Bun.write(path.join(project, name), GENERATED_BODY);
			const result = await writeFile(project, settings, name, GENERATED_NEXT);
			expect(textOf(result)).toContain("Successfully wrote");
			expect(await Bun.file(path.join(project, name)).text()).toBe(GENERATED_NEXT);
		} finally {
			await settings.close();
		}
	});

	it("does not let a non-object project edit value turn the guard off", async () => {
		for (const parent of [null, false, "", []] as const) {
			const { settings, project } = await load({
				userBlock: true,
				project: { edit: parent },
			});
			try {
				expect(settings.get("edit.blockAutoGenerated")).toBe(true);
				await Bun.write(path.join(project, GENERATED_NAME), GENERATED_BODY);
				await expect(writeFile(project, settings, GENERATED_NAME, GENERATED_NEXT)).rejects.toThrow(
					/Cannot modify auto-generated file/,
				);
				expect(await Bun.file(path.join(project, GENERATED_NAME)).text()).toBe(GENERATED_BODY);
			} finally {
				await settings.close();
			}
		}
	});

	it("still ignores a parent directory settings file", async () => {
		const { settings, project } = await load({
			makeProjectDir: false,
			parentProject: { edit: { blockAutoGenerated: false } },
		});
		try {
			expect(settings.get("edit.blockAutoGenerated")).toBe(true);
			await Bun.write(path.join(project, GENERATED_NAME), GENERATED_BODY);
			await expect(writeFile(project, settings, GENERATED_NAME, GENERATED_NEXT)).rejects.toThrow(
				/Cannot modify auto-generated file/,
			);
			expect(await Bun.file(path.join(project, GENERATED_NAME)).text()).toBe(GENERATED_BODY);
		} finally {
			await settings.close();
		}
	});

	it("property: project edit.blockAutoGenerated values stay operator-owned, fc.property seed 62817, numRuns 64", async () => {
		const leaf = fc.oneof(
			fc.boolean(),
			fc.constant(null),
			fc.constant(0),
			fc.constant(""),
			fc.constant("false"),
			fc.string({ maxLength: 12 }),
		);
		const userChoice = fc.constantFrom("unset", "true", "false");
		const surface = fc.constantFrom("settings" as const, "config" as const);
		await fc.assert(
			fc.asyncProperty(leaf, userChoice, surface, async (projectLeaf, user, via) => {
				const { settings, project } = await load({
					userBlock: user === "unset" ? undefined : user === "true",
					surface: via,
					project: { edit: { blockAutoGenerated: projectLeaf, streamingAbort: true } },
				});
				try {
					const expected = user !== "false";
					expect(settings.get("edit.blockAutoGenerated")).toBe(expected);
					expect(settings.get("edit.streamingAbort")).toBe(true);
					await Bun.write(path.join(project, GENERATED_NAME), GENERATED_BODY);
					if (expected) {
						await expect(writeFile(project, settings, GENERATED_NAME, GENERATED_NEXT)).rejects.toThrow(
							/Cannot modify auto-generated file/,
						);
						expect(await Bun.file(path.join(project, GENERATED_NAME)).text()).toBe(GENERATED_BODY);
					} else {
						const result = await writeFile(project, settings, GENERATED_NAME, GENERATED_NEXT);
						expect(textOf(result)).toContain("Successfully wrote");
					}
				} finally {
					await settings.close();
				}
			}),
			{ seed: SEED, numRuns: 64 },
		);
	});
});
