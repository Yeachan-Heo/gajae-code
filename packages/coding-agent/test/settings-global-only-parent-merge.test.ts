describe("global notification settings under a non-object parent", () => {
	for (const surface of ["settings.json", "config.yml"] as const) {
		it(`ignores a non-object project notifications value in ${surface}`, async () => {
			for (const parent of NON_OBJECT_PARENTS) {
				const settings = await loadWithProject(
					{ notifications: { enabled: true, terminalBell: true } },
					{ notifications: parent },
					surface,
				);
				try {
					expectGlobalWins(settings, { path: "notifications.enabled", value: true, globalOnly: true });
					expect(settings.get("notifications.terminalBell")).toBe(true);
				} finally {
					await settings.close();
				}
			}
		});
	}

	it("rejects a runtime notifications parent", () => {
		expect(() => Settings.isolated({}, { overrides: Object.fromEntries([["notifications", null]]) })).toThrow(
			NotificationSettingsOverrideError,
		);
		const settings = Settings.isolated({ "notifications.enabled": true });
		expect(() => overrideUntyped(settings, "notifications", null)).toThrow(NotificationSettingsOverrideError);
		expect(settings.get("notifications.enabled")).toBe(true);
	});
});

/** A valid non-default user value for a schema path, so a reset to the default is visible. */
function operatorValue(settingPath: SettingPath): unknown {
	const def = SETTINGS_SCHEMA[settingPath] as {
		type: string;
		default?: unknown;
		values?: readonly string[];
		validate?: (value: never) => boolean;
	};
	const valid = (value: unknown) => value !== def.default && (!def.validate || def.validate(value as never));
	switch (def.type) {
		case "boolean":
			return def.default !== true;
		case "enum":
			return def.values?.find(valid);
		case "number":
			return [1234, 2, 1].find(valid);
		case "string":
			return ["https://operator.example/x", "verbose", "primary"].find(valid);
		case "record":
			return { operator: "operator-value" };
		default:
			throw new Error(`add an operator value for ${def.type} setting ${settingPath}`);
	}
}

describe("every global-only schema path", () => {
	const globalOnlyPaths = (
		Object.entries(Settings.isolated({}).getResolutionSnapshot()) as [SettingPath, { allowedLayers: string[] }][]
	)
		.filter(([, resolution]) => resolution.allowedLayers.length === 1 && resolution.allowedLayers[0] === "global")
		.map(([settingPath]) => settingPath);
	const globalValues = Object.fromEntries(
		globalOnlyPaths.map(settingPath => [settingPath, operatorValue(settingPath)]),
	);
	const roots = [...new Set(globalOnlyPaths.map(rootOf))];

	it("covers the known global-only namespaces", () => {
		expect(globalOnlyPaths).toContain("plan.enabled");
		expect(globalOnlyPaths).toContain("session.ownership.mode");
		expect(globalOnlyPaths).toContain("notifications.enabled");
	});

	for (const surface of ["settings.json", "config.yml"] as const) {
		it(`keeps every user value when a project ${surface} sets each root to null`, async () => {
			let global: Record<string, unknown> = {};
			for (const settingPath of globalOnlyPaths) {
				global = mergeNested(global, nested(settingPath, globalValues[settingPath]));
			}
			const settings = await loadWithProject(global, Object.fromEntries(roots.map(root => [root, null])), surface);
			try {
				for (const settingPath of globalOnlyPaths) {
					expect({ settingPath, value: settings.getGlobal(settingPath) as unknown }).toEqual({
						settingPath,
						value: globalValues[settingPath],
					});
					expect({ settingPath, value: settings.get(settingPath) as unknown }).toEqual({
						settingPath,
						value: globalValues[settingPath],
					});
				}
			} finally {
				await settings.close();
			}
		});
	}

	it("keeps every user value when the runtime layer sets each root to null", () => {
		// The runtime layer rejects a notifications parent outright (tested above).
		const runtimeRoots = roots.filter(root => root !== "notifications");
		const viaOptions = Settings.isolated(globalValues, {
			overrides: Object.fromEntries(runtimeRoots.map(root => [root, null])),
		});
		const viaOverride = Settings.isolated(globalValues);
		for (const root of runtimeRoots) overrideUntyped(viaOverride, root, null);
		for (const settings of [viaOptions, viaOverride]) {
			for (const settingPath of globalOnlyPaths) {
				expect({ settingPath, value: settings.get(settingPath) as unknown }).toEqual({
					settingPath,
					value: settings.getGlobal(settingPath),
				});
				expect(settings.getGlobal(settingPath) as unknown).toEqual(globalValues[settingPath]);
			}
		}
	});
});

function mergeNested(base: Record<string, unknown>, extra: Record<string, unknown>): Record<string, unknown> {
	const result = { ...base };
	for (const [key, value] of Object.entries(extra)) {
		const existing = result[key];
		result[key] =
			existing && typeof existing === "object" && !Array.isArray(existing) && value && typeof value === "object"
				? mergeNested(existing as Record<string, unknown>, value as Record<string, unknown>)
				: value;
	}
	return result;
}
