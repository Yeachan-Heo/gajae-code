const NON_OBJECT_PARENTS: unknown[] = [null, "replaced", 7, []];

const roots: string[] = [];

afterEach(async () => {
	vi.restoreAllMocks();
	resetSettingsForTest();
	for (const root of roots.splice(0)) {
		await fs.rm(root, { recursive: true, force: true });
	}
});

function nested(settingPath: string, value: unknown): Record<string, unknown> {
	const root: Record<string, unknown> = {};
	let current = root;
	const segments = settingPath.split(".");
	for (const segment of segments.slice(0, -1)) {
		const next: Record<string, unknown> = {};
		current[segment] = next;
		current = next;
	}
	current[segments[segments.length - 1]!] = value;
	return root;
}

function rootOf(settingPath: string): string {
	return settingPath.split(".")[0]!;
}

async function makeDirs(): Promise<{ project: string; agent: string }> {
	const root = await fs.mkdtemp(path.join(os.tmpdir(), "gjc-global-parent-merge-"));
	roots.push(root);
	const project = path.join(root, "proj");
	const agent = path.join(root, "agent");
	await fs.mkdir(path.join(project, ".gjc"), { recursive: true });
	await fs.mkdir(agent, { recursive: true });
	return { project, agent };
}

async function loadWithProject(
	global: Record<string, unknown>,
	project: Record<string, unknown>,
	surface: "settings.json" | "config.yml",
): Promise<Settings> {
	const dirs = await makeDirs();
	await Bun.write(path.join(dirs.agent, "config.yml"), YAML.stringify(global));
	const file = path.join(dirs.project, ".gjc", surface);
	await Bun.write(file, surface === "settings.json" ? JSON.stringify(project) : YAML.stringify(project));
	return Settings.loadReadonly({ cwd: dirs.project, agentDir: dirs.agent });
}

/** `override()` is typed to schema paths but does not check them at run time; no ancestor here is a schema path. */
function overrideUntyped(settings: Settings, settingPath: string, value: unknown): void {
	settings.override(settingPath as SettingPath, value as never);
}

function expectGlobalWins(settings: Settings, entry: ProtectedCase): void {
	expect(settings.getGlobal(entry.path) as unknown).toEqual(entry.value);
	expect(settings.get(entry.path) as unknown).toEqual(entry.value);
	expect(settings.has(entry.path)).toBe(true);
	const resolution = settings.getResolutionSnapshot()[entry.path];
	expect(resolution.origin).toBe("global");
	expect(resolution.layers).toEqual(["global"]);
}

/**
 * `#migrateRawSettings` throws on a truthy scalar `hindsight`, and the loader then skips the whole
 * project layer. The user value survives either way; only the canary below cannot apply.
 */
function projectLayerSkipped(root: string, parent: unknown): boolean {
	return root === "hindsight" && (typeof parent === "string" || typeof parent === "number");
}

describe("protected settings under a non-object ancestor", () => {
	for (const entry of PROTECTED) {
		const root = rootOf(entry.path);
		for (const parent of NON_OBJECT_PARENTS) {
			const label = `${root}: ${JSON.stringify(parent)}`;
			for (const surface of ["settings.json", "config.yml"] as const) {
				it(`keeps the user ${entry.path} under a project ${surface} ${label}`, async () => {
					const settings = await loadWithProject(
						nested(entry.path, entry.value),
						{ [root]: parent, tasksPane: { defaultVisible: true } },
						surface,
					);
					try {
						expectGlobalWins(settings, entry);
						// The rest of the project file still applies.
						if (!projectLayerSkipped(root, parent)) expect(settings.get("tasksPane.defaultVisible")).toBe(true);
					} finally {
						await settings.close();
					}
				});
			}
			if (!entry.globalOnly) continue;
			it(`keeps the user ${entry.path} under options.overrides ${label}`, () => {
				const settings = Settings.isolated(
					{ [entry.path]: entry.value },
					{ overrides: Object.fromEntries([[root, parent]]) },
				);
				expectGlobalWins(settings, entry);
			});
			it(`keeps the user ${entry.path} under override() ${label}`, () => {
				const settings = Settings.isolated({ [entry.path]: entry.value });
				overrideUntyped(settings, root, parent);
				expectGlobalWins(settings, entry);
				settings.clearOverride(root as SettingPath);
				expectGlobalWins(settings, entry);
			});
		}
	}

	it("still lets a runtime override replace a project-denied path", () => {
		const settings = Settings.isolated({ "task.agentModelOverrides": { executor: "anthropic/operator-model" } });
		overrideUntyped(settings, "task", null);
		expect(settings.get("task.agentModelOverrides")).toEqual({});
		settings.override("task.agentModelOverrides", { executor: "anthropic/runtime-model" });
		expect(settings.get("task.agentModelOverrides")).toEqual({ executor: "anthropic/runtime-model" });
	});

	for (const [surface, parent] of [
		["settings.json", null],
		["config.yml", "replaced"],
		["settings.json", []],
	] as const) {
		it(`shows the user values in gjc config list under a project ${surface} parent ${JSON.stringify(parent)}`, async () => {
			const dirs = await makeDirs();
			await Bun.write(
				path.join(dirs.agent, "config.yml"),
				YAML.stringify({
					plan: { enabled: false },
					hindsight: { apiUrl: "https://hindsight.operator.example" },
					session: { ownership: { mode: "enforce" } },
				}),
			);
			// A scalar `hindsight` skips the whole project layer (see projectLayerSkipped), so it stays null.
			const project = { plan: parent, hindsight: null, session: parent };
			await Bun.write(
				path.join(dirs.project, ".gjc", surface),
				surface === "settings.json" ? JSON.stringify(project) : YAML.stringify(project),
			);
			const originalAgentDir = getAgentDir();
			const originalAgentDirEnv = process.env.GJC_CODING_AGENT_DIR;
			const originalProjectDir = getProjectDir();
			setAgentDir(dirs.agent);
			setProjectDir(dirs.project);
			try {
				const logSpy = vi.spyOn(console, "log").mockImplementation(() => {});
				await runConfigCommand({ action: "list", flags: { json: true } });
				const listed = JSON.parse(String(logSpy.mock.calls.at(-1)?.[0])) as Record<string, { value: unknown }>;
				expect(listed["plan.enabled"]?.value).toBe(false);
				expect(listed["hindsight.apiUrl"]?.value).toBe("https://hindsight.operator.example");
				expect(listed["session.ownership.mode"]?.value).toBe("enforce");
			} finally {
				resetSettingsForTest();
				setAgentDir(originalAgentDir);
				if (originalAgentDirEnv === undefined) delete process.env.GJC_CODING_AGENT_DIR;
				else process.env.GJC_CODING_AGENT_DIR = originalAgentDirEnv;
				setProjectDir(originalProjectDir);
			}
		});
	}
});

