	for (const entry of SIBLINGS) {
		it(`a project ${entry.parent}: null still resets ${entry.sibling} to its default`, async () => {
			const global = { ...nested(entry.protectedPath, entry.protectedValue) };
			const parentObject = global[entry.parent] as Record<string, unknown>;
			Object.assign(parentObject, nested(entry.sibling.slice(entry.parent.length + 1), entry.userValue));
			const settings = await loadWithProject(global, { [entry.parent]: null }, "settings.json");
			try {
				expect(settings.get(entry.sibling) as unknown).toEqual(entry.defaultValue);
				expect(settings.getResolutionSnapshot()[entry.sibling].origin).toBe("default");
				expect(settings.get(entry.protectedPath) as unknown).toEqual(entry.protectedValue);
			} finally {
				await settings.close();
			}
		});

		it(`a project ${entry.parent} object still sets ${entry.sibling}`, async () => {
			const project = {
				[entry.parent]: {
					...nested(entry.sibling.slice(entry.parent.length + 1), entry.projectValue),
					...nested(entry.protectedPath.slice(entry.parent.length + 1), "project-value"),
				},
			};
			const settings = await loadWithProject(
				nested(entry.protectedPath, entry.protectedValue),
				project,
				"config.yml",
			);
			try {
				expect(settings.get(entry.sibling) as unknown).toEqual(entry.projectValue);
				expect(settings.get(entry.protectedPath) as unknown).toEqual(entry.protectedValue);
			} finally {
				await settings.close();
			}
		});
	}

	it("a project session: null still resets non-global session keys to their defaults", async () => {
		const global = { session: { resumeModelBehavior: "ask" } };
		const reset = await loadWithProject(global, { session: null }, "settings.json");
		try {
			expect(reset.getGlobal("session.resumeModelBehavior")).toBe("ask");
			expect(reset.get("session.resumeModelBehavior")).toBe("keepSessionModel");
			expect(reset.getResolutionSnapshot()["session.resumeModelBehavior"].origin).toBe("default");
		} finally {
			await reset.close();
		}
		const set = await loadWithProject(
			global,
			{ session: { resumeModelBehavior: "useCurrentDefault" } },
			"config.yml",
		);
		try {
			expect(set.get("session.resumeModelBehavior")).toBe("useCurrentDefault");
		} finally {
			await set.close();
		}
	});

	it("a runtime override of an ancestor still replaces non-global keys", () => {
		const settings = Settings.isolated({ "plan.enabled": false, "compaction.enabled": false });
		overrideUntyped(settings, "compaction", null);
		expect(settings.get("compaction.enabled")).toBe(true);
		overrideUntyped(settings, "plan", "replaced");
		expect(settings.get("plan.enabled")).toBe(false);
	});
