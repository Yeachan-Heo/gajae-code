import { afterEach, describe, expect, it, vi } from "bun:test";
import * as fs from "node:fs/promises";
import * as os from "node:os";
import * as path from "node:path";
import { getAgentDir, getProjectDir, setAgentDir, setProjectDir } from "@gajae-code/utils";
import { YAML } from "bun";
import { runConfigCommand } from "../src/cli/config-cli";
import { NotificationSettingsOverrideError, resetSettingsForTest, Settings } from "../src/config/settings";
import type { SettingPath } from "../src/config/settings-schema";

/**
 * A project or runtime layer that sets a non-object ancestor (null, a scalar or an array) of a
 * protected path used to replace the user's whole ancestor object in the merge, so `get()` and
 * `gjc config list` fell back to the default while `getGlobal()` still held the operator value.
 */

interface ProtectedCase {
	path: SettingPath;
	/** A valid, non-default user value. */
	value: unknown;
	/** Global-only paths are protected from the runtime layer too; project-denied paths only from projects. */
	globalOnly: boolean;
}

const PROTECTED: ProtectedCase[] = [
	{ path: "crashReport.upstream", value: "sentry", globalOnly: true },
	{ path: "crashReport.upstreamDsn", value: "https://key@operator.example/1", globalOnly: true },
	{ path: "paseo.autoImport", value: true, globalOnly: true },
	{ path: "ui.language", value: "ko", globalOnly: true },
	{ path: "telemetry.enabled", value: true, globalOnly: true },
	{ path: "hindsight.apiUrl", value: "https://hindsight.operator.example", globalOnly: true },
	{ path: "compaction.remoteEndpoint", value: "https://compact.operator.example", globalOnly: true },
	{ path: "searxng.endpoint", value: "https://searxng.operator.example", globalOnly: true },
	{ path: "skills.trustProjectSkills", value: true, globalOnly: true },
	{ path: "skills.enablePiProject", value: true, globalOnly: true },
	{ path: "edit.blockAutoGenerated", value: false, globalOnly: true },
	{ path: "plan.enabled", value: false, globalOnly: true },
	{ path: "task.agentModelOverrides", value: { executor: "anthropic/operator-model" }, globalOnly: false },
	{ path: "clipboard.transport", value: "osc52", globalOnly: false },
	{ path: "clipboard.sshHost", value: "operator-host", globalOnly: false },
	{ path: "auth.credentialPins", value: { anthropic: "operator-pin" }, globalOnly: false },
	{ path: "auth.credentialPinStoreIdentity", value: "operator-store", globalOnly: false },
];

const NON_OBJECT_PARENTS: unknown[] = [null, "replaced", 7, []];

const roots: string[] = [];

afterEach(async () => {
	vi.restoreAllMocks();
	resetSettingsForTest();
	for (const root of roots.splice(0)) {
		await fs.rm(root, { recursive: true, force: true });
	}
});

function nested(settingPath: string, value: unknown): Record<string, unknown> {
	const root: Record<string, unknown> = {};
	let current = root;
	const segments = settingPath.split(".");
	for (const segment of segments.slice(0, -1)) {
		const next: Record<string, unknown> = {};
		current[segment] = next;
		current = next;
	}
	current[segments[segments.length - 1]!] = value;
	return root;
}

function rootOf(settingPath: string): string {
	return settingPath.split(".")[0]!;
}

async function makeDirs(): Promise<{ project: string; agent: string }> {
	const root = await fs.mkdtemp(path.join(os.tmpdir(), "gjc-global-parent-merge-"));
	roots.push(root);
	const project = path.join(root, "proj");
	const agent = path.join(root, "agent");
	await fs.mkdir(path.join(project, ".gjc"), { recursive: true });
	await fs.mkdir(agent, { recursive: true });
	return { project, agent };
}

async function loadWithProject(
	global: Record<string, unknown>,
	project: Record<string, unknown>,
	surface: "settings.json" | "config.yml",
): Promise<Settings> {
	const dirs = await makeDirs();
	await Bun.write(path.join(dirs.agent, "config.yml"), YAML.stringify(global));
	const file = path.join(dirs.project, ".gjc", surface);
	await Bun.write(file, surface === "settings.json" ? JSON.stringify(project) : YAML.stringify(project));
	return Settings.loadReadonly({ cwd: dirs.project, agentDir: dirs.agent });
}

/** `override()` is typed to schema paths but does not check them at run time; no ancestor here is a schema path. */
function overrideUntyped(settings: Settings, settingPath: string, value: unknown): void {
	settings.override(settingPath as SettingPath, value as never);
}

function expectGlobalWins(settings: Settings, entry: ProtectedCase): void {
	expect(settings.getGlobal(entry.path) as unknown).toEqual(entry.value);
	expect(settings.get(entry.path) as unknown).toEqual(entry.value);
	const resolution = settings.getResolutionSnapshot()[entry.path];
	expect(resolution.origin).toBe("global");
	expect(resolution.layers).toEqual(["global"]);
}

/**
 * `#migrateRawSettings` throws on a truthy scalar `hindsight`, and the loader then skips the whole
 * project layer. The user value survives either way; only the canary below cannot apply.
 */
function projectLayerSkipped(root: string, parent: unknown): boolean {
	return root === "hindsight" && (typeof parent === "string" || typeof parent === "number");
}

describe("protected settings under a non-object ancestor", () => {
	for (const entry of PROTECTED) {
		const root = rootOf(entry.path);
		for (const parent of NON_OBJECT_PARENTS) {
			const label = `${root}: ${JSON.stringify(parent)}`;
			for (const surface of ["settings.json", "config.yml"] as const) {
				it(`keeps the user ${entry.path} under a project ${surface} ${label}`, async () => {
					const settings = await loadWithProject(
						nested(entry.path, entry.value),
						{ [root]: parent, tasksPane: { defaultVisible: true } },
						surface,
					);
					try {
						expectGlobalWins(settings, entry);
						// The rest of the project file still applies.
						if (!projectLayerSkipped(root, parent)) expect(settings.get("tasksPane.defaultVisible")).toBe(true);
					} finally {
						await settings.close();
					}
				});
			}
			if (!entry.globalOnly) continue;
			it(`keeps the user ${entry.path} under options.overrides ${label}`, () => {
				const settings = Settings.isolated(
					{ [entry.path]: entry.value },
					{ overrides: Object.fromEntries([[root, parent]]) },
				);
				expectGlobalWins(settings, entry);
			});
			it(`keeps the user ${entry.path} under override() ${label}`, () => {
				const settings = Settings.isolated({ [entry.path]: entry.value });
				overrideUntyped(settings, root, parent);
				expectGlobalWins(settings, entry);
				settings.clearOverride(root as SettingPath);
				expectGlobalWins(settings, entry);
			});
		}
	}

	it("still lets a runtime override replace a project-denied path", () => {
		const settings = Settings.isolated({ "task.agentModelOverrides": { executor: "anthropic/operator-model" } });
		overrideUntyped(settings, "task", null);
		expect(settings.get("task.agentModelOverrides")).toEqual({});
		settings.override("task.agentModelOverrides", { executor: "anthropic/runtime-model" });
		expect(settings.get("task.agentModelOverrides")).toEqual({ executor: "anthropic/runtime-model" });
	});

	it("shows the user value in gjc config list", async () => {
		const dirs = await makeDirs();
		await Bun.write(
			path.join(dirs.agent, "config.yml"),
			YAML.stringify({ plan: { enabled: false }, hindsight: { apiUrl: "https://hindsight.operator.example" } }),
		);
		await Bun.write(
			path.join(dirs.project, ".gjc", "settings.json"),
			JSON.stringify({ plan: null, hindsight: null }),
		);
		const originalAgentDir = getAgentDir();
		const originalAgentDirEnv = process.env.GJC_CODING_AGENT_DIR;
		const originalProjectDir = getProjectDir();
		setAgentDir(dirs.agent);
		setProjectDir(dirs.project);
		try {
			const logSpy = vi.spyOn(console, "log").mockImplementation(() => {});
			await runConfigCommand({ action: "list", flags: { json: true } });
			const listed = JSON.parse(String(logSpy.mock.calls.at(-1)?.[0])) as Record<string, { value: unknown }>;
			expect(listed["plan.enabled"]?.value).toBe(false);
			expect(listed["hindsight.apiUrl"]?.value).toBe("https://hindsight.operator.example");
		} finally {
			resetSettingsForTest();
			setAgentDir(originalAgentDir);
			if (originalAgentDirEnv === undefined) delete process.env.GJC_CODING_AGENT_DIR;
			else process.env.GJC_CODING_AGENT_DIR = originalAgentDirEnv;
			setProjectDir(originalProjectDir);
		}
	});
});

describe("non-protected keys under a replaced ancestor merge as before", () => {
	const SIBLINGS: {
		parent: string;
		protectedPath: SettingPath;
		protectedValue: unknown;
		sibling: SettingPath;
		userValue: unknown;
		projectValue: unknown;
		defaultValue: unknown;
	}[] = [
		{
			parent: "hindsight",
			protectedPath: "hindsight.apiUrl",
			protectedValue: "https://hindsight.operator.example",
			sibling: "hindsight.bankId",
			userValue: "operator-bank",
			projectValue: "project-bank",
			defaultValue: undefined,
		},
		{
			parent: "compaction",
			protectedPath: "compaction.remoteEndpoint",
			protectedValue: "https://compact.operator.example",
			sibling: "compaction.enabled",
			userValue: false,
			projectValue: false,
			defaultValue: true,
		},
		{
			parent: "skills",
			protectedPath: "skills.trustProjectSkills",
			protectedValue: true,
			sibling: "skills.enabled",
			userValue: false,
			projectValue: false,
			defaultValue: true,
		},
		{
			parent: "edit",
			protectedPath: "edit.blockAutoGenerated",
			protectedValue: false,
			sibling: "edit.fuzzyMatch",
			userValue: false,
			projectValue: false,
			defaultValue: true,
		},
		{
			parent: "task",
			protectedPath: "task.agentModelOverrides",
			protectedValue: { executor: "anthropic/operator-model" },
			sibling: "task.serviceTier",
			userValue: "flex",
			projectValue: "priority",
			defaultValue: "inherit",
		},
		{
			parent: "auth",
			protectedPath: "auth.credentialPins",
			protectedValue: { anthropic: "operator-pin" },
			sibling: "auth.credentialRankingMode",
			userValue: "earliest-reset",
			projectValue: "earliest-reset",
			defaultValue: "balanced",
		},
	];

	for (const entry of SIBLINGS) {
		it(`a project ${entry.parent}: null still resets ${entry.sibling} to its default`, async () => {
			const global = { ...nested(entry.protectedPath, entry.protectedValue) };
			const parentObject = global[entry.parent] as Record<string, unknown>;
			Object.assign(parentObject, nested(entry.sibling.slice(entry.parent.length + 1), entry.userValue));
			const settings = await loadWithProject(global, { [entry.parent]: null }, "settings.json");
			try {
				expect(settings.get(entry.sibling) as unknown).toEqual(entry.defaultValue);
				expect(settings.getResolutionSnapshot()[entry.sibling].origin).toBe("default");
				expect(settings.get(entry.protectedPath) as unknown).toEqual(entry.protectedValue);
			} finally {
				await settings.close();
			}
		});

		it(`a project ${entry.parent} object still sets ${entry.sibling}`, async () => {
			const project = {
				[entry.parent]: {
					...nested(entry.sibling.slice(entry.parent.length + 1), entry.projectValue),
					...nested(entry.protectedPath.slice(entry.parent.length + 1), "project-value"),
				},
			};
			const settings = await loadWithProject(
				nested(entry.protectedPath, entry.protectedValue),
				project,
				"config.yml",
			);
			try {
				expect(settings.get(entry.sibling) as unknown).toEqual(entry.projectValue);
				expect(settings.get(entry.protectedPath) as unknown).toEqual(entry.protectedValue);
			} finally {
				await settings.close();
			}
		});
	}

	it("a project session: null still resets non-global session keys to their defaults", async () => {
		const global = { session: { resumeModelBehavior: "ask" } };
		const reset = await loadWithProject(global, { session: null }, "settings.json");
		try {
			expect(reset.getGlobal("session.resumeModelBehavior")).toBe("ask");
			expect(reset.get("session.resumeModelBehavior")).toBe("keepSessionModel");
			expect(reset.getResolutionSnapshot()["session.resumeModelBehavior"].origin).toBe("default");
		} finally {
			await reset.close();
		}
		const set = await loadWithProject(
			global,
			{ session: { resumeModelBehavior: "useCurrentDefault" } },
			"config.yml",
		);
		try {
			expect(set.get("session.resumeModelBehavior")).toBe("useCurrentDefault");
		} finally {
			await set.close();
		}
	});

	it("a runtime override of an ancestor still replaces non-global keys", () => {
		const settings = Settings.isolated({ "plan.enabled": false, "compaction.enabled": false });
		overrideUntyped(settings, "compaction", null);
		expect(settings.get("compaction.enabled")).toBe(true);
		overrideUntyped(settings, "plan", "replaced");
		expect(settings.get("plan.enabled")).toBe(false);
	});
});

describe("global notification settings under a non-object parent", () => {
	for (const surface of ["settings.json", "config.yml"] as const) {
		it(`ignores a non-object project notifications value in ${surface}`, async () => {
			for (const parent of NON_OBJECT_PARENTS) {
				const settings = await loadWithProject(
					{ notifications: { enabled: true, terminalBell: true } },
					{ notifications: parent },
					surface,
				);
				try {
					expectGlobalWins(settings, { path: "notifications.enabled", value: true, globalOnly: true });
					expect(settings.get("notifications.terminalBell")).toBe(true);
				} finally {
					await settings.close();
				}
			}
		});
	}

	it("rejects a runtime notifications parent", () => {
		expect(() => Settings.isolated({}, { overrides: Object.fromEntries([["notifications", null]]) })).toThrow(
			NotificationSettingsOverrideError,
		);
		const settings = Settings.isolated({ "notifications.enabled": true });
		expect(() => overrideUntyped(settings, "notifications", null)).toThrow(NotificationSettingsOverrideError);
		expect(settings.get("notifications.enabled")).toBe(true);
	});
});
