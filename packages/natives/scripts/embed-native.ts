import * as fs from "node:fs/promises";
import * as path from "node:path";
import { verifyDiagnosticArtifactDigest } from "./diagnostic-artifact-manifest";
import {
	type BuildSidecar,
	type CandidateAddon,
	missingRequiredFunctions,
	verifyDefaultLanguageSet,
} from "./embed-guard";

export type EmbeddedAddonVariant = CandidateAddon["variant"];

const validEmbedVariants = new Set<EmbeddedAddonVariant>(["modern", "baseline", "default"]);
const outputPath = path.join(import.meta.dir, "../native/embedded-addon.js");
const diagnosticArtifactOutputPath = path.join(import.meta.dir, "../native/diagnostic-artifact-embedded.json");
const packageJsonPath = path.join(import.meta.dir, "../package.json");
const nativeDir = path.join(import.meta.dir, "../native");
const emptyDiagnosticArtifactContent = `${JSON.stringify(
	{ schema: "gjc.diagnostic-artifact", version: "", artifacts: {} },
	null,
	2,
)}\n`;

const stubContent = `
// AUTOGENERATED FILE -- DO NOT EDIT DIRECTLY
// See scripts/embed-native.ts

/** @typedef {"modern" | "baseline" | "default"} EmbeddedAddonVariant */

/**
 * @typedef {Object} EmbeddedAddonFile
 * @property {EmbeddedAddonVariant} variant
 * @property {string} filename
 * @property {string} filePath
 */

/**
 * @typedef {Object} EmbeddedAddon
 * @property {string} platformTag
 * @property {string} version
 * @property {EmbeddedAddonFile[]} files
 */

/** @type {EmbeddedAddon|null} */
export const embeddedAddon = null;
`;

const requiredAddonExports = [
	"nativeBuildInfo",
	"probeWindowsJobMemory",
	"currentExecutablePath",
	"readOwnerOnlyFile",
] as const;

export function missingRequiredAddonExports(bindings: Record<string, unknown>): string[] {
	return missingRequiredFunctions(bindings, requiredAddonExports);
}

export function parseEmbedVariants(value: string | undefined): Set<EmbeddedAddonVariant> | null {
	if (!value) {
		return null;
	}

	const variants = value
		.split(",")
		.map(variant => variant.trim())
		.filter(Boolean);
	const unknownVariants = variants.filter(variant => !validEmbedVariants.has(variant as EmbeddedAddonVariant));
	if (unknownVariants.length > 0) {
		throw new Error(
			`Invalid EMBED_VARIANTS value(s): ${unknownVariants.join(", ")}. Valid values are: modern, baseline, default.`,
		);
	}

	return new Set(variants as EmbeddedAddonVariant[]);
}

export function buildCandidateList(targetArch: string, platformTag: string): CandidateAddon[] {
	return targetArch === "x64"
		? [
				{ variant: "modern", filename: `pi_natives.${platformTag}-modern.node` },
				{ variant: "baseline", filename: `pi_natives.${platformTag}-baseline.node` },
			]
		: [{ variant: "default", filename: `pi_natives.${platformTag}.node` }];
}

export function filterCandidatesByVariant(
	candidates: CandidateAddon[],
	requestedVariants: Set<EmbeddedAddonVariant> | null,
	platformTag: string,
): CandidateAddon[] {
	if (!requestedVariants) {
		return candidates;
	}

	const filtered = candidates.filter(candidate => requestedVariants.has(candidate.variant));
	if (filtered.length === 0) {
		throw new Error(
			`EMBED_VARIANTS selected no candidates for ${platformTag}. Requested: ${[...requestedVariants].join(", ")}; available variants for target: ${candidates.map(candidate => candidate.variant).join(", ")}.`,
		);
	}
	return filtered;
}

export function filterStaleLocalCandidates(
	candidates: CandidateAddon[],
	buildSidecars: ReadonlyMap<string, BuildSidecar | null>,
	packageVersion: string,
	explicitlyRequestedVariants: ReadonlySet<EmbeddedAddonVariant> | null,
): CandidateAddon[] {
	const currentCandidates: CandidateAddon[] = [];
	for (const candidate of candidates) {
		const sidecar = buildSidecars.get(candidate.filename);
		if (sidecar?.profile === "local" && sidecar.version !== undefined && sidecar.version !== packageVersion) {
			if (explicitlyRequestedVariants?.has(candidate.variant)) {
				throw new Error(
					`${candidate.filename} is a local build for @gajae-code/natives@${sidecar.version}; rebuild it for @gajae-code/natives@${packageVersion} before embedding`,
				);
			}
			continue;
		}
		currentCandidates.push(candidate);
	}
	return currentCandidates;
}

async function readBuildSidecar(candidatePath: string): Promise<BuildSidecar | null> {
	const sidecarPath = `${candidatePath}.build.json`;
	try {
		return (await Bun.file(sidecarPath).json()) as BuildSidecar;
	} catch (err) {
		if ((err as NodeJS.ErrnoException).code === "ENOENT") return null;
		throw err;
	}
}

async function fileExists(filePath: string): Promise<boolean> {
	try {
		await fs.stat(filePath);
		return true;
	} catch (err) {
		if ((err as NodeJS.ErrnoException).code === "ENOENT") return false;
		throw err;
	}
}

async function embedNative(): Promise<void> {
	// Restoring the constant null stub neither selects nor reads an addon, so it stays
	// available even when a present artifact has no trusted record. Every real embedding
	// below still passes the provenance gate before any require or output mutation.
	if (process.argv.includes("--reset")) {
		await Bun.write(outputPath, stubContent);
		await Bun.write(diagnosticArtifactOutputPath, emptyDiagnosticArtifactContent);
		return;
	}

	const targetPlatform = Bun.env.TARGET_PLATFORM || process.platform;
	const targetArch = Bun.env.TARGET_ARCH || process.arch;
	const platformTag = `${targetPlatform}-${targetArch}`;
	const hostPlatformTag = `${process.platform}-${process.arch}`;
	const requestedVariants = parseEmbedVariants(Bun.env.EMBED_VARIANTS);
	const selectedCandidates = filterCandidatesByVariant(
		buildCandidateList(targetArch, platformTag),
		requestedVariants,
		platformTag,
	);
	const packageJson = (await Bun.file(packageJsonPath).json()) as { version: string };

	const existingCandidates: CandidateAddon[] = [];
	const buildSidecars = new Map<string, BuildSidecar | null>();
	for (const candidate of selectedCandidates) {
		const candidatePath = path.join(nativeDir, candidate.filename);
		if (!(await fileExists(candidatePath))) continue;
		existingCandidates.push(candidate);
		buildSidecars.set(candidate.filename, await readBuildSidecar(candidatePath));
	}
	const candidates = filterStaleLocalCandidates(
		existingCandidates,
		buildSidecars,
		packageJson.version,
		requestedVariants,
	);
	const currentCandidateNames = new Set(candidates.map(candidate => candidate.filename));
	for (const candidate of existingCandidates) {
		if (currentCandidateNames.has(candidate.filename)) continue;
		const sidecar = buildSidecars.get(candidate.filename);
		if (sidecar?.profile === "local" && sidecar.version !== undefined) {
			console.warn(
				`Skipping stale local native addon ${candidate.filename} built for @gajae-code/natives@${sidecar.version}; rebuild it for @gajae-code/natives@${packageJson.version} to embed it.`,
			);
		}
	}

	const verifiedCandidates: Array<{ candidate: CandidateAddon; candidatePath: string; digest: string }> = [];
	for (const candidate of candidates) {
		const candidatePath = path.join(nativeDir, candidate.filename);
		const digest = await verifyDiagnosticArtifactDigest({
			addonPath: candidatePath,
			nativeDir,
			version: packageJson.version,
			allowLocalBuilds: true,
		});
		verifiedCandidates.push({ candidate, candidatePath, digest });
	}

	const available: CandidateAddon[] = [];
	const diagnosticArtifacts: Record<string, string> = {};
	for (const { candidate, candidatePath, digest } of verifiedCandidates) {
		const nativeBindings =
			platformTag === hostPlatformTag ? (require(candidatePath) as Record<string, unknown>) : undefined;
		await verifyDefaultLanguageSet(candidate, candidatePath, {
			platformTag,
			hostPlatformTag,
			readBuildSidecar,
			loadNativeAddon: () => nativeBindings as { nativeBuildInfo?: () => { languageSet?: string } },
			warn: message => console.warn(message),
		});
		if (nativeBindings) {
			const missingExports = missingRequiredAddonExports(nativeBindings);
			if (missingExports.length > 0) {
				throw new Error(
					`Embedded addon candidate ${candidate.filename} is missing required exports: ${missingExports.join(", ")}`,
				);
			}
		}
		available.push(candidate);
		diagnosticArtifacts[candidate.filename] = digest;
	}

	if (available.length === 0) {
		const expected = selectedCandidates.map(candidate => `  - ${candidate.filename}`).join("\n");
		throw new Error(`No native addons found for ${platformTag}. Expected one of:\n${expected}`);
	}

	const imports = available
		.map(
			(candidate, index) =>
				`import addonPath${index} from ${JSON.stringify(`../native/${candidate.filename}`)} with { type: "file" };`,
		)
		.join("\n");

	const files = available
		.map(
			(candidate, index) =>
				`\t\t{ variant: ${JSON.stringify(candidate.variant)}, filename: ${JSON.stringify(candidate.filename)}, filePath: addonPath${index} },`,
		)
		.join("\n");

	const content = `
// AUTOGENERATED FILE -- DO NOT EDIT DIRECTLY
// See scripts/embed-native.ts

/** @typedef {"modern" | "baseline" | "default"} EmbeddedAddonVariant */

/**
 * @typedef {Object} EmbeddedAddonFile
 * @property {EmbeddedAddonVariant} variant
 * @property {string} filename
 * @property {string} filePath
 */

/**
 * @typedef {Object} EmbeddedAddon
 * @property {string} platformTag
 * @property {string} version
 * @property {EmbeddedAddonFile[]} files
 */

${imports}

export const embeddedAddon = {
	platformTag: ${JSON.stringify(platformTag)},
	version: ${JSON.stringify(packageJson.version)},
	files: [
${files}
	],
};
`;

	await Bun.write(outputPath, content);
	await Bun.write(
		diagnosticArtifactOutputPath,
		`${JSON.stringify(
			{ schema: "gjc.diagnostic-artifact", version: packageJson.version, artifacts: diagnosticArtifacts },
			null,
			2,
		)}\n`,
	);
}

if (import.meta.main) {
	await embedNative();
}
